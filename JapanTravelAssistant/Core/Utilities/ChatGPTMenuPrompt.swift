import Foundation

/// 給使用者複製到 ChatGPT（或任何 AI）的提示文字，以及對應的輸出格式。
/// 格式刻意設計成「一行一道菜、用 | 隔開」：人看得懂，也容易貼回 App 解析。
enum ChatGPTMenuPrompt {
    static let startMarker = "菜單開始"
    static let endMarker = "菜單結束"

    static let text = """
    請幫我翻譯這張日本餐廳菜單的照片，給不懂日文的台灣家人看。

    請嚴格照下面的格式輸出，不要加任何說明、標題或其他文字：

    菜單開始
    分類 | 日文分類名稱 | 繁體中文分類名稱
    日文原名 | 繁體中文翻譯 | 價格 | 一句簡短說明 | 羅馬拼音
    選項 | 選項群組 | 日文選項 | 中文選項 | 價差
    菜單結束

    規則：
    1. 一定要分類。每個分類用「分類 | 日文分類 | 中文分類」單獨一行（第一格固定寫「分類」兩個字），後面接這個分類的菜。
       菜單上有分類就照菜單的；沒有的話請你依照類型分（例如 前菜、炸物、烤物、主食、飲料）。
       不要用 # 或粗體之類的 markdown 標題。
    2. 每道菜一行，欄位用「|」隔開，順序固定：日文原名、繁體中文、價格、說明、羅馬拼音。
       羅馬拼音用平文式（Hepburn），例如 とんかつ → tonkatsu、唐揚げ → karaage，讓家人可以唸給店員聽。
    3. 日文原名照菜單上的字寫，不要翻譯、不要改字。
    4. 繁體中文要讓台灣人一看就懂是什麼菜（例如 唐揚げ → 日式炸雞）。
    5. 價格只寫數字（例如 540）。有含稅價就寫含稅價；沒有價格就留空。
    6. 說明 15 個字以內，介紹食材或口味；不需要就留空。
    7. 直排的菜單請由右往左、由上往下讀。
    8. 如果一道菜可以選份量、選單點或套餐、加價升級、換配料，請在那道菜的下一行用
       「選項 | 群組 | 日文選項 | 中文選項 | 價差」列出每一個選項，第一格固定寫「選項」兩個字。
       群組用中文（例如 份量、套餐、配料），價差寫相對於上面價格的加減金額（例如 +150、-100、0）。
       例如：
       とんかつ | 炸豬排 | 540 |
       選項 | 份量 | 大盛り | 大份 | +150
       選項 | 套餐 | 単品 | 單點 | 0
       選項 | 套餐 | 定食セット | 升級定食（附飯、湯、小菜） | +300
       同一個群組只能選一個。菜單上寫「定食 +300円」「大盛り無料」「ライス大盛り +100」都算選項。
    9. 看不清楚的字盡量猜，不要跳過任何一道菜。
    10. 不要用表格，不要用程式碼區塊，直接輸出純文字。
    """
}
