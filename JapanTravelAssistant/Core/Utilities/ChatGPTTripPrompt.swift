/// 丟給「討論行程的那個 ChatGPT 對話」的提示文字：把整趟行程的地點整理成可匯入的格式。
enum ChatGPTTripPrompt {
    static let startMarker = "行程開始"
    static let endMarker = "行程結束"

    static let text = """
    請把我們在這個對話裡討論好的日本行程，整理成下面的格式，我要匯入手機 App。
    嚴格照格式輸出，不要加任何說明、標題或其他文字，不要用表格或 markdown。

    行程開始
    行程 | 行程名稱 | 開始日期 | 結束日期
    天 | 第1天 | 日期 | 當天城市或主題
    地點 | 中文名稱 | 日文正式名稱 | 日文地址（含郵遞區號） | 類型 | 一句備註
    推薦 | 中文名稱 | 日文正式名稱 | 日文地址（含郵遞區號） | 類型 | 為什麼推薦
    行程結束

    規則：
    1. 第一行「行程」：名稱用中文（例如 9月名古屋親子遊），日期寫 YYYY-MM-DD，不確定就留空。
    2. 每一天先寫一行「天」，後面接那天會去的地點，照當天的順序排。
    3. 每個地點一行，欄位用「|」隔開，順序固定：中文名稱、日文正式名稱、日文地址、類型、備註。
